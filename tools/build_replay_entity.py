#!/usr/bin/env python3
"""Ahead-of-time JS for trusted procedural formulas; no runtime bytecode dispatch/eval."""
import ast,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
tree=ast.parse((ROOT/'tools/replay-entity.hvm').read_text())
draw=next(f for f in tree.body if f.name=='draw')
globals_={n.id for n in ast.walk(draw) if isinstance(n,ast.Name) and isinstance(n.ctx,ast.Store)}|{a.arg for a in draw.args.args}
globals_.discard('unused')
ops={ast.Add:'add',ast.Sub:'sub',ast.Mult:'mul',ast.Div:'div'}
def expr(n):
 if isinstance(n,ast.Constant):return repr(n.value)
 if isinstance(n,ast.Name):return 'Math.PI' if n.id=='pi' else n.id
 if isinstance(n,ast.Subscript):return f'rig[{expr(n.slice)}]'
 if isinstance(n,ast.UnaryOp):return f'neg({expr(n.operand)})'
 if isinstance(n,ast.BinOp):return f'{ops[type(n.op)]}({expr(n.left)},{expr(n.right)})'
 if isinstance(n,ast.Compare):return f'({expr(n.left)} {"<" if isinstance(n.ops[0],ast.Lt) else "==="} {expr(n.comparators[0])})'
 if isinstance(n,ast.IfExp):return f'({expr(n.test)}?{expr(n.body)}:{expr(n.orelse)})'
 if isinstance(n,ast.Call):
  name=n.func.id
  if name in ('sin','cos','abs','sqrt','pow','min','max'):name='Math.'+name
  return f'{name}({",".join(map(expr,n.args))})'
 raise ValueError(ast.dump(n))
def statements(nodes,depth=1):
 lines=[];pad=' '*depth
 for n in nodes:
  if isinstance(n,ast.Assign):
   target=expr(n.targets[0]);lines.append(pad+(expr(n.value) if target=='unused' else target+'='+expr(n.value))+';')
  elif isinstance(n,ast.Return):lines.append(pad+'return '+expr(n.value)+';')
  elif isinstance(n,ast.If):
   lines.extend([pad+'if('+expr(n.test)+'){',statements(n.body,depth+1),pad+'}'])
   if n.orelse:lines.extend([pad+'else{',statements(n.orelse,depth+1),pad+'}'])
  elif isinstance(n,ast.For):lines.extend([pad+f'for({expr(n.target)}=0;{expr(n.target)}<{expr(n.iter.args[0])};{expr(n.target)}++)'+'{',statements(n.body,depth+1),pad+'}'])
  elif isinstance(n,ast.Expr):lines.append(pad+expr(n.value)+';')
  else:raise ValueError(ast.dump(n))
 return '\n'.join(lines)
head='''// Generated by tools/build_replay_entity.py. Edit tools/replay-entity.hvm.
const vector=Array.isArray;
const add=(a,b)=>vector(a)?[a[0]+b[0],a[1]+b[1],a[2]+b[2]]:a+b;
const sub=(a,b)=>vector(a)?[a[0]-b[0],a[1]-b[1],a[2]-b[2]]:a-b;
const mul=(a,b)=>vector(a)?[a[0]*b,a[1]*b,a[2]*b]:a*b;
const div=(a,b)=>vector(a)?[a[0]/b,a[1]/b,a[2]/b]:a/b;
const neg=a=>vector(a)?[-a[0],-a[1],-a[2]]:-a;
const vec=(x,y,z)=>[x,y,z],dot=(a,b)=>a[0]*b[0]+a[1]*b[1]+a[2]*b[2];
const cross=(a,b)=>[a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]];
const rem=(a,b)=>(a%b+b)%b;
export function createEntityModel(){
 const rig=Array.from({length:19},()=>[0,0,0]);let vertices=[],particles=[];
 const emit=(out,a,b,c,d)=>{for(const p of [a,b,c,a,c,d])out.push(p[0],p[1],-p[2]);};
 const quad=(a,b,c,d)=>emit(vertices,a,b,c,d),rage_quad=(a,b,c,d)=>emit(particles,a,b,c,d);
'''
parts=[head,' let '+','.join(sorted(globals_))+';']
for f in tree.body:
 args=[a.arg for a in f.args.args];local={n.id for n in ast.walk(f) if isinstance(n,ast.Name) and isinstance(n.ctx,ast.Store)}-set(args)-{'unused'}
 if f.name=='draw':
  parts.append(' function draw('+','.join(a+'_' for a in args)+'){')
  parts.append('  '+''.join(a+'='+a+'_;' for a in args))
 else:
  parts.append(' function '+f.name+'('+','.join(args)+'){')
  if local:parts.append('  let '+','.join(sorted(local))+';')
 parts.extend([statements(f.body,2),' }'])
parts.append(' return (...args)=>{vertices=[];particles=[];draw(...args);return {vertices,particles,rig:rig.slice(0,16)};};\n}\n')
out='\n'.join(parts);target=ROOT/'web/replay/entity-model.js'
if '--check' in sys.argv:assert target.read_text()==out
else:target.write_text(out)
