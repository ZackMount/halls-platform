import assert from 'node:assert/strict';
import {scoreComponents,referenceTime} from '../web/score-breakdown.js';
const html=scoreComponents({components:{completion:10,pace:34.567,coins:10,tactics:0,integrity:-5},componentMaxima:{completion:10,pace:50,coins:30,tactics:10}});
assert.equal((html.match(/class="score-earned"/g)||[]).length,4);
assert.ok(html.includes('>10</strong><span class="score-maximum">/ 30</span>'));
assert.ok(html.includes('>34.57</strong><span class="score-maximum">/ 50</span>'));
assert.ok(html.includes('>0</strong><span class="score-maximum">/ 10</span>'));
assert.ok(!html.includes('-5'),'adjustments are not positive score components');
const zero=scoreComponents({components:{completion:0},componentMaxima:{completion:0}});
assert.ok(zero.includes('>0</strong><span class="score-maximum">/ 0</span>'));
const custom=scoreComponents({components:{coins:12},componentMaxima:{coins:40}});
assert.ok(custom.includes('>12</strong><span class="score-maximum">/ 40</span>'));
const unknown=scoreComponents({components:{coins:10}});
assert.ok(unknown.includes('/ —</span>'),'unknown historical weights must not be guessed');
assert.ok(!scoreComponents({components:{coins:'<script>x</script>'},componentMaxima:{coins:NaN}}).includes('<script>'));
console.log('Saved component maxima, compact numeric formatting, zero values and unknown limits passed');
assert.equal(referenceTime({available:true,seconds:59.999}),'01:00.00');
assert.equal(referenceTime({available:true,seconds:190.890245}),'03:10.89');
assert.equal(referenceTime({available:true,seconds:0}),'00:00.00');
for(const seconds of [-1,NaN,Infinity,true,'4',86400.01])assert.equal(referenceTime({available:true,seconds}),'');
const withReference=scoreComponents({components:{pace:20,coins:10},raceReference:{available:true,seconds:190.890245,approximate:true}});
assert.ok(withReference.includes('理论最短时间'));
assert.ok(withReference.includes('<span>约</span> 03:10.89'));
assert.ok(withReference.indexOf('竞速')<withReference.indexOf('理论最短时间')&&withReference.indexOf('理论最短时间')<withReference.indexOf('金币'));
assert.ok(!scoreComponents({components:{pace:20},raceReference:{available:false}}).includes('理论最短时间'));
assert.ok(!scoreComponents({components:{pace:20},raceReference:{available:true,seconds:0,approximate:false}}).includes('<span>约</span>'));
console.log('Saved reference timing, approximation, rounding rollover and pace-row placement passed');
